# Користувач вводить два числа, що представляють діапазон.
# Програма повинна пройти по діапазону і вивести добуток усіх чисел,
# які діляться на 4, але не діляться на 6. Якщо таких чисел немає,
# вивести відповідне повідомлення. Діапазон має автоматично
# нормалізуватися, якщо початок більший за кінець.
start = int(input("Enter start: "))
finish = int(input("Enter finish: "))
for i in range(start, finish+1):
    if i % 4 == 0 and not i % 6 != 0:
        print(i*i)
    else:
        print("Not number")
