# Користувач вводить із клавіатури два числа (початок і кінець
# діапазону). Потрібно проаналізувати всі числа в цьому діапазоні.
# Виведення на екран має відбуватися за правилами, зазначеними нижче.
# Якщо число кратне 3 (ділиться на 3 без залишку) потрібно
# вивести слово "Fizz". Якщо число кратне 5 потрібно вивести слово
# "Buzz". Якщо число кратне 3 і 5 потрібно вивести "Fizz Buzz".
# Якщо число не кратне не 3 і 5 потрібно вивести саме число.
start = int(input("Enter start: "))
finish = int(input("Enter finish: "))
for i in range(start, finish+1):
    if i % 3 == 0 and not i % 5 == 0:
        print("Fizz")
    elif i % 5 == 0 and not i % 3 == 0:
        print("Buzz")
    elif i % 3 == 0 and i % 5 == 0:
        print("Fizz Buzz")
    else:
        print(i)
