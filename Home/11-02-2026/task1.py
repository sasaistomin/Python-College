# Користувач вводить два числа: число A і ступінь N, у який потрібно
# піднести число. Програма повинна обчислити A у степені N за допомогою
# циклу (без використання вбудованих функцій піднесення до степеня).
a = int(input("Enter a number: "))
n = int(input("Enter a number: "))
result = 1
