# Напишіть функцію, що обчислює добуток елементів списку цілих. Список
# передається як параметр. Отриманий результат повертається з функції.
def Mylti(arr):
    myl = 1
    for i in arr:
        myl *= i
    return myl


arr = [1, 2, 3, 4, 5]
print(Mylti(arr))
